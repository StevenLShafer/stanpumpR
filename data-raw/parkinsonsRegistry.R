# -----------------------------------------------------------------------------
# Build inst/extdata/parkinsonsRegistry.csv, parkinsonsProducts.csv and
# parkinsonsParameters.csv
# -----------------------------------------------------------------------------
# Drafted by Claude Code, 2026-10-19, at the request of Steven L. Shafer, who
# asked for the drugs used to treat Parkinson's disease, with their times of
# peak effect and therapeutic ranges, the influence of patient covariates
# including genotype, and the literature and product monographs (EMA, FDA)
# that explain their pharmacokinetics, pharmacodynamics and onset.
#
# THREE TABLES
# ============
# parkinsonsProducts.csv  one row per product (drug and formulation): what
#                         its US label and the literature say about its time
#                         to peak concentration, half-life, onset and time of
#                         peak effect, therapeutic range, covariates and
#                         genotype, with the label it came from.  The clinical
#                         summary, whether or not a model is in the library.
# parkinsonsRegistry.csv  one row per drug and candidate source model: its
#                         readiness, the library drug that implements it (if
#                         any), what blocks it and the paper that would
#                         unblock it.  Readiness:
#
#   implemented        in the library as a selectable drug
#   complete_not_implemented
#                      a complete model read and checked, not offered: an
#                      alternative to an implemented source, or one whose own
#                      evidence is too weak to plot (the reason is given)
#   needs_full_text    a candidate model exists, but the numbers that fix it
#                      could not be read here (abstract only, or tables
#                      missing from the text that was retrieved)
#   needs_engine       a complete model read whose input or route the
#                      engine does not carry (transdermal, inhaled, a chain
#                      of transit compartments, an inverse Gaussian input)
#   no_suitable_model  no published model this library could use
#
# parkinsonsParameters.csv  every number of every implemented model, with its
#                         units, provenance and source.
#
# `evidence_read` records what was read in this environment: the full text
# (PubMed Central, or an FDA review or label from accessdata.fda.gov), the
# abstract only, the label only, or nothing beyond a citation.  The European
# Medicines Agency's site, DailyMed, Europe PMC and the publishers were not
# reachable from here, so every EMA product information document is cited,
# where one exists, as a document to read, and none was read.
#
# Run with: Rscript data-raw/parkinsonsRegistry.R
# Checked by tests/testthat/test-parkinsons-registry.R.
# -----------------------------------------------------------------------------

