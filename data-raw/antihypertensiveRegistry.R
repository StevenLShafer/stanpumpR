# docs/antihypertensives.md for that audit, including the places where the
# handoff's own numbers or claims were corrected.
#
# WHAT THIS REGISTRY IS
# =====================
# One row per MODEL RECORD, not per drug: a record is a molecule in one
# formulation by one route, and -- where a source fitted something -- in one
# population for one endpoint from one publication.  Propranolol IR and
# propranolol LA are two records; furosemide tablet and furosemide injection
# are two records; the three clevidipine studies are three records because
# they share no population, matrix or endpoint.
#
# The registry exists so that LISTING A DRUG NEVER IMPLIES A RUNNABLE MODEL.
# Most antihypertensives in routine use have no published, internally
# consistent concentration-to-blood-pressure fit at all, and most of the ones
# that do fitted an endpoint that is not resting blood pressure (exercise
# systolic pressure, exercise heart rate, isoproterenol-induced tachycardia,
# urinary sodium, ACE inhibition, a vascular-resistance proxy, or the
# probability of crossing a mean-pressure threshold).  Every row therefore
# carries independent evidence fields rather than one "validated" flag, and
# bp_simulation_enabled is FALSE everywhere in this release: the package
# plots concentrations, and no blood-pressure curve is drawn for any drug.
#
# FIELDS (vocabularies fixed by the specification)
# ================================================
#   model_id      molecule__formulation__route__population__endpoint__source
#   pk_evidence,  primary_fitted_full      all coefficients the structure needs,
#   pd_evidence                            from one internally consistent fit
#                 primary_fitted_partial   a fit, but not all coefficients
#                 primary_structure_only   a structure, no usable numbers
#                 official_label_descriptive  label PK descriptors only
#                 proposed_unfitted        nothing fitted
#                 secondary_transcription_unverified  (pd only) numbers taken
#                                          from a secondary transcription
#   execution_status  ready_for_source_reproduction | requires_source_extraction
#                     | requires_parameter_fit | descriptive_only
#   bp_simulation_enabled  TRUE only when the whole dose -> PK -> blood
#                     pressure chain, its baseline and its measurement context
#                     are populated AND source reproduction passes.  Nothing
#                     qualifies yet.
#   external_validation_status  none | in_population | external_population
#   stanpumpr_drug    the library drug implementing this record, or NA.  A
#                     named drug plots CONCENTRATION only.
#
# Run with: Rscript data-raw/antihypertensiveRegistry.R
# Checked by tests/testthat/test-antihypertensive-registry.R.
# -----------------------------------------------------------------------------

# pk_evidence / pd_evidence
FULL <- "primary_fitted_full"
PART <- "primary_fitted_partial"
STRU <- "primary_structure_only"
LAB  <- "official_label_descriptive"
PRO  <- "proposed_unfitted"
SEC  <- "secondary_transcription_unverified"
# execution_status
READY <- "ready_for_source_reproduction"
EXTR  <- "requires_source_extraction"
FITP  <- "requires_parameter_fit"
DESC  <- "descriptive_only"

rec <- function(model_id, drug, active_moiety, route, formulation,
                population = NA, endpoint = "none", analyte = NA,
                matrix = NA, pk_evidence = LAB, pd_evidence = PRO,
                execution_status = DESC, bp_simulation_enabled = FALSE,
                external_validation_status = "none", stanpumpr_drug = NA,
                source_type = "official_label", source_url, limitations)
  data.frame(model_id, drug, active_moiety, route, formulation, population,
             endpoint, analyte, matrix, pk_evidence, pd_evidence,
             execution_status, bp_simulation_enabled,
             external_validation_status, stanpumpr_drug, source_type,
             source_url, limitations, stringsAsFactors = FALSE)

