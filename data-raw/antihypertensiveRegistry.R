# -----------------------------------------------------------------------------
# estimate_status  fitted | fixed | derived | label_descriptive | proposed
# reported_or_derived  reported (as printed in the source) | derived (computed
#                  here from reported quantities, with the derivation in the
#                  drug file header or docs/antihypertensives.md)
# uncertainty_type the type the SOURCE ITSELF names.  "not_reported" where the
#                  source prints a +/- but never says what it is -- which is
#                  the honest answer for several of these papers and must not
#                  be upgraded to SD or SE by assumption.
# verification     primary_full_text   read in the full text
#                  primary_abstract    read in the source's own abstract
#                  derived_here        computed from verified numbers
#                  handoff_unverified  from the handoff specification only;
#                                      this container cannot reach the
#                                      publisher, so it is NOT checked
# A number marked handoff_unverified is data in a catalog, never an input to
# anything this package computes.

par <- function(model_id, parameter, value, unit, estimate_status,
                reported_or_derived = "reported", uncertainty = NA,
                uncertainty_type = "not_reported", matrix = NA,
                population = NA, endpoint = NA, source_url,
                source_table_or_page = NA, verification, notes = NA)
  data.frame(model_id, parameter, value, unit, estimate_status,
             reported_or_derived, uncertainty, uncertainty_type, matrix,
             population, endpoint, source_url, source_table_or_page,
             verification, notes, stringsAsFactors = FALSE)

