registry <- rbind(catalog, sources)
# Radix order, so that the generated files are byte-identical whatever the
# collation locale of the machine that rebuilds them: the default order() is
# locale-dependent, and a C-locale and a UTF-8 run otherwise shuffle the rows
# of a file under version control.
registry <- registry[order(registry$drug, registry$model_id,
                           method = "radix"), ]
rownames(registry) <- NULL
parameters <- parameters[order(parameters$model_id, parameters$parameter,
                               method = "radix"), ]
rownames(parameters) <- NULL

# Internal consistency, so the CSVs cannot be written in a broken state.  The
# same invariants are asserted again by the test suite against the shipped
# files.
stopifnot(
  !any(duplicated(registry$model_id)),
  all(registry$pk_evidence %in% c(FULL, PART, STRU, LAB, PRO)),
  all(registry$pd_evidence %in% c(FULL, PART, STRU, LAB, PRO, SEC)),
  all(registry$execution_status %in% c(READY, EXTR, FITP, DESC)),
  all(registry$external_validation_status %in%
        c("none", "in_population", "external_population")),
  all(grepl("^https?://", registry$source_url)),
  # No blood pressure is simulated anywhere in this release.
  !any(registry$bp_simulation_enabled),
  # Every parameter belongs to a registry record.
  all(parameters$model_id %in% registry$model_id),
  all(parameters$estimate_status %in%
        c("fitted", "fixed", "derived", "label_descriptive", "proposed")),
  all(parameters$reported_or_derived %in% c("reported", "derived")),
  all(parameters$verification %in% c("primary_full_text", "primary_abstract",
                                     "derived_here", "handoff_unverified")),
  # A record this package executes must not rest on an unverified number.
  !any(parameters$verification == "handoff_unverified" &
         parameters$model_id %in%
           registry$model_id[registry$execution_status == READY])
)

